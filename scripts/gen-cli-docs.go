var (
	flagRE    = regexp.MustCompile(`^(?:-\w, )?--([\w-]+)(?: (\S+))?\s{2,}(.+)$`)
	defaultRE = regexp.MustCompile(`^(.*) \(default (.+)\)$`)
	commandRE = regexp.MustCompile(`^(\S+)\s+(.+)$`)
	angleRE   = regexp.MustCompile(`<[^<>\s]+>`)
)

func main() {
	out := flag.String("out", "docs/reference/cli.md", "output path")
	check := flag.Bool("check", false, "fail instead of write when output differs")
	sluice := flag.String("sluice", "bin/sluice", "path to the sluice binary")
	flag.Parse()

	var buf bytes.Buffer
	buf.WriteString(strings.ReplaceAll(header, "~", "`"))
	count := walk(&buf, *sluice, nil, "", nil)

	if *check {
		cur, err := os.ReadFile(*out)
		if err != nil {
			fatal("read existing: %v", err)
		}
		if !bytes.Equal(cur, buf.Bytes()) {
			fmt.Fprintln(os.Stderr, "cli.md drift: run `make docs-generate`")
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*out, buf.Bytes(), 0o644); err != nil {
		fatal("write %s: %v", *out, err)
	}
	fmt.Printf("wrote %s (%d commands)\n", *out, count)
}

// walk renders the command at path, or its subcommands when it has some.
// short is the one-line description from the parent's command list, alts
// holds other spellings of path. It returns the number of sections written.
func walk(buf *bytes.Buffer, sluice string, path []string, short string, alts []string) int {
	help, err := exec.Command(sluice, append(path, "--help")...).Output()
	if err != nil {
		fatal("%s --help: %v", strings.Join(append([]string{sluice}, path...), " "), err)
	}
	parts := sections(string(help))

	// "Aliases:" lists the command name first, then its aliases.
	if len(path) > 0 && len(parts["Aliases"]) > 0 {
		parent := strings.Join(path[:len(path)-1], " ")
		for _, alias := range strings.Split(parts["Aliases"][0], ", ")[1:] {
			alts = append(alts, strings.TrimSpace(parent+" "+alias))
		}
	}

	if subs := parts["Available Commands"]; len(subs) > 0 {
		count := 0
		for _, line := range subs {
			m := commandRE.FindStringSubmatch(line)
			if m == nil {
				fatal("%s: cannot read command line %q", strings.Join(path, " "), line)
			}
			if m[1] == "help" || m[1] == "completion" {
				continue
			}
			var subAlts []string
			for _, a := range alts {
				subAlts = append(subAlts, a+" "+m[1])
			}
			count += walk(buf, sluice, append(path[:len(path):len(path)], m[1]), m[2], subAlts)
		}
		return count
	}

	name := strings.Join(path, " ")
	if len(parts["Usage"]) == 0 {
		fatal("%s: no usage line in the help text", name)
	}
	fmt.Fprintf(buf, "\n## %s\n\n%s.\n\n", name, strings.TrimSuffix(text(short), "."))
	fmt.Fprintf(buf, "`%s`\n", parts["Usage"][0])
	for _, a := range alts {
		fmt.Fprintf(buf, "\nShort form: `sluice %s`\n", a)
	}

	var rows []string
	for _, line := range parts["Flags"] {
		m := flagRE.FindStringSubmatch(line)
		if m == nil {
			fatal("%s: cannot read flag line %q", name, line)
		}
		if m[1] == "help" {
			continue
		}
		typ, meaning, def := m[2], m[3], ""
		if typ == "" {
			typ = "bool" // the help text names no type for a bool flag
		}
		if d := defaultRE.FindStringSubmatch(meaning); d != nil {
			meaning, def = d[1], "`"+strings.Trim(d[2], `"`)+"`"
		}
		rows = append(rows, fmt.Sprintf("| `--%s` | %s | %s | %s |", m[1], typ, def, text(meaning)))
	}
	if len(rows) > 0 {
		buf.WriteString("\n| Flag | Type | Default | Meaning |\n|---|---|---|---|\n")
		buf.WriteString(strings.Join(rows, "\n") + "\n")
	}
	if note, ok := notes[name]; ok {
		buf.WriteString("\n" + strings.ReplaceAll(note, "~", "`") + "\n")
	}
	return 1
}

// sections splits the help text from the last "Usage:" line on into its
// parts, keyed by the header without the colon. The lines are trimmed.
func sections(help string) map[string][]string {
	lines := strings.Split(help, "\n")
	start := 0
	for i, line := range lines {
		if line == "Usage:" {
			start = i
		}
	}
	out := map[string][]string{}
	key := ""
	for _, line := range lines[start:] {
		switch {
		case strings.TrimSpace(line) == "":
			key = ""
		case !strings.HasPrefix(line, " ") && strings.HasSuffix(line, ":"):
			key = strings.TrimSuffix(line, ":")
		case key != "":
			out[key] = append(out[key], strings.TrimSpace(line))
		}
	}
	return out
}

// text prepares a help text for a Markdown table cell or paragraph.
func text(s string) string {
	if o, ok := overrides[s]; ok {
		s = o
	}
	s = strings.ReplaceAll(s, "|", `\|`)
	// A bare <name> would be read as an HTML tag.
	return angleRE.ReplaceAllString(s, "`$0`")
}

func fatal(f string, args ...any) {
	fmt.Fprintf(os.Stderr, f+"\n", args...)
	os.Exit(1)
}
