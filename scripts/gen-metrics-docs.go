// gen-metrics-docs renders docs/reference/metrics.md. It parses every
// non-test .go file under internal/ and pkg/ with go/ast and collects the
// metric definitions: telemetry.Define{Counter,Histogram,Gauge} and
// prometheus.New{Counter,Histogram,Gauge}[Vec]. Reading the source keeps
// the generator free of cgo and of process state. Run via `make
// docs-generate`; `make docs-check` fails when the page differs.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

type metricDecl struct {
	Name   string
	Type   string
	Help   string
	Labels []string
}

// skip lists metrics that the code defines but a server never exports.
// An entry that ends with "_" is a prefix.
var skip = []string{}

// skipLabels lists labels that are always empty.
var skipLabels = map[string][]string{
	"sluice_build_info": {"instance", "environment"}, // ServiceInfo never sets them
}

// meaning replaces a help text that is too long for a table cell.
var meaning = map[string]string{
	"sluice_rest_rate_limited_total": "REST requests refused by `limits.globalRps` or `limits.perIpRps`.",
}

const header = `<!-- SPDX-License-Identifier: CC-BY-4.0 -->
<!-- Generated by scripts/gen-metrics-docs.go. Do not edit by hand. -->

# Metrics

Sluice serves Prometheus metrics at ` + "`GET /metrics`" + ` on the [admin API](admin-api.md).

| Metric | Type | Labels | Meaning |
|---|---|---|---|
`

const footer = `
- Sluice also exports the Go runtime metrics (` + "`go_*`" + `) and the process metrics (` + "`process_*`" + `).
- The ` + "`sluice_approval_*`" + ` metrics exist only when ` + "`approval.publicBaseUrl`" + ` is set.
- A counter with labels appears after its first event.
- The ` + "`sluice_policy_*`" + ` metrics count the YAML engine only, also as a member of ` + "`composite`" + `.
`

func main() {
	out := flag.String("out", "docs/reference/metrics.md", "output path")
	check := flag.Bool("check", false, "fail instead of write when output differs")
	flag.Parse()

	var all []metricDecl
	for _, r := range []string{"internal", "pkg"} {
		ms, err := walkTree(r)
		if err != nil {
			fatal("walk %s: %v", r, err)
		}
		all = append(all, ms...)
	}

	used := map[string]bool{}
	var metrics []metricDecl
	for _, m := range all {
		if s := skipEntry(m.Name); s != "" {
			used[s] = true
			continue
		}
		metrics = append(metrics, m)
	}
	for _, s := range skip {
		if !used[s] {
			fatal("skip entry %q matches no metric: remove it", s)
		}
	}
	slices.SortFunc(metrics, func(a, b metricDecl) int { return strings.Compare(a.Name, b.Name) })

	var buf bytes.Buffer
	buf.WriteString(header)
	for _, m := range metrics {
		var labels []string
		for _, l := range m.Labels {
			if !slices.Contains(skipLabels[m.Name], l) {
				labels = append(labels, "`"+l+"`")
			}
		}
		help := m.Help
		if h, ok := meaning[m.Name]; ok {
			help = h
		}
		fmt.Fprintf(&buf, "| `%s` | %s | %s | %s |\n",
			m.Name, m.Type, strings.Join(labels, ", "), escapePipe(help))
	}
	buf.WriteString(footer)

	abs, err := filepath.Abs(*out)
	if err != nil {
		fatal("resolve path: %v", err)
	}

	if *check {
		cur, err := os.ReadFile(abs)
		if err != nil {
			fatal("read existing: %v", err)
		}
		if !bytes.Equal(cur, buf.Bytes()) {
			fmt.Fprintln(os.Stderr, "metrics.md drift: run `make docs-generate`")
			os.Exit(1)
		}
		return
	}

	if err := os.WriteFile(abs, buf.Bytes(), 0o644); err != nil {
		fatal("write %s: %v", abs, err)
	}
	fmt.Printf("wrote %s\n", abs)
}

// skipEntry returns the skip entry that covers name, or "".
func skipEntry(name string) string {
	for _, s := range skip {
		if name == s || strings.HasSuffix(s, "_") && strings.HasPrefix(name, s) {
			return s
		}
	}
	return ""
}

// walkTree parses every non-test .go file under root and collects
// telemetry.Define* call sites.
func walkTree(root string) ([]metricDecl, error) {
	var out []metricDecl
	err := filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() {
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		ms, err := parseFile(path)
		if err != nil {
			return err
		}
		out = append(out, ms...)
		return nil
	})
	return out, err
}

func parseFile(path string) ([]metricDecl, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
	if err != nil {
		return nil, err
	}

	var out []metricDecl
	ast.Inspect(f, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		sel, ok := call.Fun.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		x, ok := sel.X.(*ast.Ident)
		if !ok {
			return true
		}

		if x.Name == "telemetry" {
			if m, ok := decodeTelemetryCall(sel.Sel.Name, call.Args); ok {
				out = append(out, m)
			}
			return true
		}
		if x.Name == "prometheus" {
			if m, ok := decodePrometheusCall(sel.Sel.Name, call.Args); ok {
				out = append(out, m)
			}
			return true
		}
		return true
	})
	return out, nil
}

// decodeTelemetryCall handles telemetry.Define{Counter,Histogram,Gauge}
// call signatures: (name, help, labels, [buckets]).
func decodeTelemetryCall(fn string, args []ast.Expr) (metricDecl, bool) {
	var kind string
	switch fn {
	case "DefineCounter":
		kind = "counter"
	case "DefineHistogram":
		kind = "histogram"
	case "DefineGauge":
		kind = "gauge"
	default:
		return metricDecl{}, false
	}
	if len(args) < 3 {
		return metricDecl{}, false
	}
	name, ok := stringLiteral(args[0])
	if !ok {
		return metricDecl{}, false
	}
	help, _ := stringLiteral(args[1])
	return metricDecl{
		Name: name, Type: kind, Help: help,
		Labels: stringSliceLiteral(args[2]),
	}, true
}

// decodePrometheusCall handles direct prometheus.New{Counter,Histogram,Gauge}
// calls and their Vec forms: (opts) or (opts, labels). A call whose Name is
// not a string literal is skipped (the telemetry.Define* helpers).
func decodePrometheusCall(fn string, args []ast.Expr) (metricDecl, bool) {
	var kind string
	switch strings.TrimSuffix(fn, "Vec") {
	case "NewCounter":
		kind = "counter"
	case "NewHistogram":
		kind = "histogram"
	case "NewGauge":
		kind = "gauge"
	default:
		return metricDecl{}, false
	}
	if len(args) < 1 {
		return metricDecl{}, false
	}
	// Arg is a {Counter,Histogram,Gauge}Opts composite literal carrying
	// Name + Help fields.
	comp, ok := args[0].(*ast.CompositeLit)
	if !ok {
		return metricDecl{}, false
	}
	var name, help string
	for _, e := range comp.Elts {
		kv, ok := e.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		key, ok := kv.Key.(*ast.Ident)
		if !ok {
			continue
		}
		switch key.Name {
		case "Name":
			name, _ = stringLiteral(kv.Value)
		case "Help":
			help, _ = stringLiteral(kv.Value)
		}
	}
	if name == "" {
		return metricDecl{}, false
	}
	m := metricDecl{Name: name, Type: kind, Help: help}
	if len(args) > 1 {
		m.Labels = stringSliceLiteral(args[1])
	}
	return m, true
}

func stringLiteral(e ast.Expr) (string, bool) {
	l, ok := e.(*ast.BasicLit)
	if !ok || l.Kind != token.STRING {
		return "", false
	}
	v, err := unquote(l.Value)
	if err != nil {
		return "", false
	}
	return v, true
}

// unquote handles both interpreted (`"…"`) and raw (`…`) string literals —
// telemetry call sites use interpreted strings today but raw is allowed.
func unquote(s string) (string, error) {
	if len(s) >= 2 && (s[0] == '`' && s[len(s)-1] == '`') {
		return s[1 : len(s)-1], nil
	}
	return strconvUnquote(s)
}

// strconvUnquote is a local, dependency-light stand-in for strconv.Unquote
// — which would be fine to import, but keeping the dependency set tiny
// makes the generator easier to audit.
func strconvUnquote(s string) (string, error) {
	if len(s) < 2 || s[0] != '"' || s[len(s)-1] != '"' {
		return "", fmt.Errorf("unquote: bad format %q", s)
	}
	// Escaping inside telemetry help strings is limited to \n/\t/\"; a
	// naive Replace is sufficient for the metrics we ship.
	r := strings.NewReplacer(`\"`, `"`, `\n`, "\n", `\t`, "\t", `\\`, `\`)
	return r.Replace(s[1 : len(s)-1]), nil
}

func stringSliceLiteral(e ast.Expr) []string {
	// Accept:
	//   nil
	//   []string{"a", "b"}
	if id, ok := e.(*ast.Ident); ok && id.Name == "nil" {
		return nil
	}
	comp, ok := e.(*ast.CompositeLit)
	if !ok {
		return nil
	}
	var out []string
	for _, elt := range comp.Elts {
		if s, ok := stringLiteral(elt); ok {
			out = append(out, s)
		}
	}
	return out
}

func escapePipe(s string) string {
	return strings.ReplaceAll(s, "|", `\|`)
}

func fatal(f string, args ...any) {
	fmt.Fprintf(os.Stderr, f+"\n", args...)
	os.Exit(1)
}
